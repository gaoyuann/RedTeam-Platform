import {taskScope,isTargetInScope} from './taskScope.js';
import {createHash} from 'node:crypto';
import {builtinVerificationPlans,evaluateFindingRule,directoryEvidenceCriteria} from './findingVerificationRules.js';
import {verificationObservation} from './findingVerificationEvidence.js';
const parse=(v,f=null)=>{try{return typeof v==='string'?JSON.parse(v):v??f;}catch{return f;}};
const hash=v=>createHash('sha256').update(JSON.stringify(v)).digest('hex');
const titles={headers:'确认指定防护响应头配置缺陷',cookie:'确认指定 Cookie 安全属性缺失',directory:'确认指定目录索引暴露'};
const registered=r=>r && builtinVerificationPlans.some(p=>p.id===r.id&&p.kind===r.kind)
  && (r.kind==='directory'?[1,2].includes(r.version):r.version===1);
function accessOnly(plan) {
  return !plan.assessment_rule && Array.isArray(plan.steps) && plan.steps.length>0 && plan.steps.every(s=>{
    if(!s || s.tool_id!=='target-request' || ![undefined,'none'].includes(s.consumption)
        || s.payload_id || s.payload_snapshot || s.reference_payload_id
        || Object.keys(s.payload_variables || {}).length)return false;
    const args=parse(s.args_template,[]);
    if(!Array.isArray(args) || args.length!==1 || typeof args[0]!=='string' || /\{\{|\}\}/.test(args[0]))return false;
    const spec=parse(args[0]);
    if(!spec || typeof spec!=='object' || Array.isArray(spec)
        || Object.keys(spec).some(k=>!['url','method','timeout_ms','max_bytes'].includes(k))
        || !['GET','HEAD'].includes(spec.method || 'GET'))return false;
    const target=spec.url==='<target>'?plan.target:spec.url;
    if(typeof target!=='string' || target.trim()!==target || !/^https?:\/\//i.test(target) || /\{\{|\}\}/.test(target))return false;
    try {
      const url=new URL(target);
      return ['http:','https:'].includes(url.protocol) && !url.username && !url.password && !url.search && !url.hash
        && !target.includes('?') && !target.includes('#') && !target.includes('\\');
    }catch{return false;}
  });
}
export function normalizeVerificationObjectiveDraft(value) {
  if(value===undefined)return undefined;
  if(!value || typeof value!=='object' || Array.isArray(value)
      || Object.keys(value).some(k=>!['label','category'].includes(k))
      || typeof value.label!=='string' || !value.label.trim() || value.label.length>200
      || !['accessibility','configuration_exposure','effect'].includes(value.category))
    throw Object.assign(new Error('验证目标草稿须含非空且不超过 200 字的 label，以及有效的 category；不能声明判定能力'),{status:400});
  return {label:value.label.trim(),category:value.category};
}
// This contract is generated by the service, never accepted from AI or request JSON.
export function buildVerificationContract(plan,findingId) {
  const rule=registered(plan.assessment_rule)?plan.assessment_rule:null;
  const steps=plan.steps || [],draft=normalizeVerificationObjectiveDraft(plan.objective_draft);
  return {schema_version:1,object:{finding_id:findingId,target:plan.target},
    objective:{id:rule?.id || (draft?`objective_${hash({finding_id:findingId,target:plan.target,...draft}).slice(0,24)}`:'unavailable_effect'),
      category:rule?'configuration_exposure':draft?.category || (accessOnly(plan)?'accessibility':'effect'),
      label:rule?titles[rule.kind]:draft?.label || (accessOnly(plan)?'页面可访问性检查（不证明其他安全影响）':'效果验证目标尚未具备受支持判据')},
    operations:steps.map(s=>({step_id:s.step_id,step_index:s.step_index,tool_id:s.tool_id,name:s.name})),
    capability:{automatic:!!rule,reason:rule?null:'尚无适用的验证方案或自动效果判据'},
    criterion:rule?{id:rule.id,version:rule.version,step_id:rule.step_id,required_evidence:['same_attempt','same_entry','complete_response'],supports_negative:true}:null,
    limitations:rule?.limitations || '现有操作不能证明其他安全影响；人工意见不替代自动验证结论。'};
}
export const legacyConclusion=result=>({achieved:'confirmed',not_achieved:'not_verified',inconclusive:'inconclusive'}[result.status] || 'pending');

// Pure read projection: a saved assessment and its original evidence are both required.
export function projectVerificationResult(db,item,attempt,assessment) {
  const frozen=db.prepare('SELECT content,fingerprint FROM finding_verification_plans WHERE verification_id=? AND revision=?').get(item.id,attempt?.revision ?? item.revision);
  const plan=parse(frozen?.content,{}) || {},contract=plan.verification_contract;
  const base={schema_version:1,status:'inconclusive',reason_code:'missing_contract',reason:'历史目标未明确，证据不足',
    object:contract?.object || {finding_id:item.finding_id,target:plan.target || null},
    objective:contract?.objective || {id:null,category:'unknown',label:'历史验证目标未记录'},
    criterion:contract?.criterion || null,evidence_ids:[],operations:[],observed_facts:[],checks:[],unverified:[],limitations:contract?.limitations || '未证明其他安全影响'};
  const finish=(status,code,reason)=>({...base,status,reason_code:code,reason,unverified:status==='achieved'?[base.limitations]:[reason,base.limitations]});
  if(!attempt)return finish('not_performed','no_attempt','尚未开展适用验证');
  const run=db.prepare('SELECT * FROM execution_runs WHERE run_id=?').get(attempt.run_id);
  const pipeline=db.prepare('SELECT * FROM pipelines WHERE pipeline_id=?').get(attempt.pipeline_id);
  const link=parse(run?.plan_data,{})?.finding_verification;
  let inScope=false;try{inScope=!!pipeline && isTargetInScope(taskScope(pipeline),plan.target);}catch{}
  if(!frozen || !Array.isArray(plan.steps) || plan.steps.some(s=>!s || typeof s!=='object') || !inScope || hash(plan)!==frozen.fingerprint || run?.user_sub!==pipeline?.created_by || run?.target!==plan.target
      || link?.attempt_id!==attempt.id || link?.verification_id!==item.id || link?.finding_id!==item.finding_id
      || link?.pipeline_id!==attempt.pipeline_id || link?.revision!==attempt.revision || link?.fingerprint!==frozen.fingerprint)
    return finish('inconclusive','source_mismatch','执行与冻结方案的来源无法可靠核对');
  const evidence=db.prepare('SELECT * FROM evidence_records WHERE run_id=? ORDER BY id DESC').all(attempt.run_id);
  const eligible=evidence.filter(e=>{
    const data=parse(e.evidence_data,{}),l=data?.finding_verification;
    const call=e.attempt_id?db.prepare('SELECT run_id,step_index,tool_id FROM execution_attempts WHERE id=?').get(e.attempt_id):null;
    if(contract && (!call || call.run_id!==attempt.run_id || call.step_index!==e.step_index || call.tool_id!==e.tool_id || e.target!==plan.target))return false;
    const step=plan.steps?.find(s=>s.step_index===e.step_index && s.tool_id===e.tool_id);
    return step && l?.attempt_id===attempt.id && l?.verification_id===item.id && l?.finding_id===item.finding_id
      && l?.pipeline_id===attempt.pipeline_id && l?.revision===attempt.revision && l?.fingerprint===frozen.fingerprint
      && (step.consumption!=='independent' || l.tool_started===false
        || l.payload_version===step.payload_version && l.payload_consumed===true && data.payload_id===step.payload_id);
  });
  base.operations=(plan.steps || []).map(s=>{
    const rows=eligible.filter(e=>e.step_index===s.step_index && e.tool_id===s.tool_id);
    const flags=rows.map(e=>parse(e.evidence_data,{}).finding_verification.tool_started);
    return {step_id:s.step_id,step_index:s.step_index,tool_id:s.tool_id,name:s.name,
      started:flags.includes(true)?true:flags.length&&flags.every(f=>f===false)?false:null,evidence_ids:rows.map(e=>e.id)};
  });
  for(const e of eligible) {
    const o=verificationObservation(e);
    if(o)base.observed_facts.push({evidence_id:e.id,url:o.url,method:o.method,status_code:o.status_code,complete:o.complete,received_bytes:o.received_bytes});
  }
  if(!contract) {
    if(accessOnly(plan) && eligible.length && base.observed_facts.length===eligible.length) {
      base.objective={id:null,category:'accessibility',label:'页面可访问性检查（不证明其他安全影响）'};
      return finish('not_performed','legacy_accessibility_only','未开展适用的效果验证；已保存的操作仅提供页面请求观察');
    }
    return finish('inconclusive','missing_contract','历史目标未明确，证据不足；历史判断仅供参考');
  }
  let expectedContract;try{expectedContract=buildVerificationContract(plan,item.finding_id);}catch{}
  if(contract.schema_version!==1 || JSON.stringify(contract)!==JSON.stringify(expectedContract))
    return finish('inconclusive','invalid_contract','验证契约不受支持或与冻结方案不一致');
  if(['queued','running','cancelling'].includes(attempt.state))return finish('pending','awaiting_result','操作尚未结束，等待完整证据');
  if(attempt.state==='unknown' || !attempt.stop_confirmed)return finish('inconclusive','stop_unconfirmed','实际停止状态未确认，无法作出验证结论');
  if(parse(run.final_summary,{})?.verification_dispatch_started===false && !base.operations.some(s=>s.started===true))
    return finish('not_performed','dispatch_not_started','执行器尚未派发适用操作，未开展验证');
  if(run.preflight_status==='FAILED' && !base.operations.some(s=>s.started===true)
      || base.operations.length && base.operations.every(s=>s.started===false))
    return finish('not_performed','not_started','预检或执行约束阻止了适用操作，未开展验证');
  if(!contract.capability.automatic) {
    return accessOnly(plan)?finish('not_performed','accessibility_only','未开展适用的效果验证；页面请求不能证明其他安全影响')
      :finish('inconclusive','unsupported_criterion','已有相关操作，但尚无适用的自动效果判据');
  }
  if(attempt.state!=='completed' || run.status!=='COMPLETED')return finish('inconclusive','execution_incomplete','操作未完整完成，不能将执行异常当成目标未达成');
  const latestSteps=new Map(db.prepare('SELECT step_index,tool_id,success FROM execution_steps WHERE run_id=? ORDER BY id').all(attempt.run_id).map(s=>[s.step_index,s]));
  if(plan.steps.some(s=>latestSteps.get(s.step_index)?.tool_id!==s.tool_id || latestSteps.get(s.step_index)?.success!==1))
    return finish('inconclusive','required_steps_incomplete','必要步骤缺少完整成功执行记录，不能据单个响应确认目标达成');
  const rule=plan.assessment_rule,ids=parse(assessment?.evidence_ids,[]);
  if(!assessment || assessment.rule_id!==rule.id || assessment.rule_version!==rule.version || !Array.isArray(ids) || !ids.length
      || !ids.every(id=>eligible.some(e=>e.id===id)))return finish('inconclusive','assessment_missing','缺少同一目标、规则版本及尝试的有效自动判断证据');
  const required=base.operations.find(s=>s.step_id===contract.criterion.step_id);
  if(required?.started!==true)return finish('inconclusive','start_unproven','缺少适用工具实际启动的证据');
  const referenced=eligible.filter(e=>ids.includes(e.id));
  if(base.operations.some(s=>s.started!==true) || referenced.some(e=>parse(e.evidence_data,{}).finding_verification.tool_started!==true))return finish('inconclusive','start_unproven','必要步骤或判定证据缺少实际启动证明');
  if(base.operations.some(s=>{
    const latest=eligible.find(e=>e.step_index===s.step_index && e.tool_id===s.tool_id),data=parse(latest?.evidence_data,{});
    return data.success!==true || data.exit_code!==0;
  }))return finish('inconclusive','required_evidence_failed','必要步骤的执行证据缺失或明确失败，不能确认目标达成');
  if(referenced.some(e=>typeof parse(e.raw_stdout,{})?.response!=='string'))
    return finish('inconclusive','response_body_missing','缺少完整 HTML 观察，不能排除认证页或可靠核对检查对象');
  // A complete HTTP transfer is not necessarily a complete document. Keep the
  // saved rule result intact, but do not promote no-content or partial pages.
  if(['headers','directory'].includes(rule.kind) && referenced.some(e=>{
    const observation=parse(e.raw_stdout,{});
    return [204,205,206].includes(observation.status_code) || !observation.response.trim()
      || observation.response_headers?.['content-range']!==undefined;
  }))return finish('inconclusive','document_incomplete','响应没有可用于本目标的完整页面；无内容或部分内容不能证明目标达成或未达成');
  const evaluated=evaluateFindingRule(rule,referenced,{...attempt,fingerprint:frozen.fingerprint},{...plan,finding_id:item.finding_id});
  base.checks=referenced.flatMap(e=>directoryEvidenceCriteria(rule,e,{...attempt,fingerprint:frozen.fingerprint},{...plan,finding_id:item.finding_id})?.checks || []);
  if(evaluated.conclusion!==assessment.conclusion || evaluated.conclusion==='inconclusive')return finish('inconclusive','evidence_inadequate',evaluated.reason || '保存的结论与效果证据不一致');
  base.evidence_ids=ids;
  if(evaluated.conclusion==='confirmed')return finish('achieved','criteria_met',assessment.reason);
  if(evaluated.conclusion==='not_verified' && contract.criterion.supports_negative)return finish('not_achieved','negative_criteria_met',assessment.reason);
  return finish('inconclusive','negative_unsupported','当前规则不具备可靠的负向判定能力');
}
